/* Vertebra landmark targets, derived once from the shipped skeleton's own vertices and committed as
 *   work/bone-landmark-vertebrae.mjs
 * (node work/derive-vertebra-landmarks.mjs). The NAMES come from the W4 Head, Neck & Trunk deck: p19 (atlas: superior
 * articular facet), p20 (a cervical vertebra, C3-C6), p22 (thoracic), p26 (lumbar). The POSITIONS are app-authored
 * annotations: extreme or nearest vertices measured on each vertebra, then reviewed on screen. Never rebuild blind:
 * if the GLB changes, bone-landmarks.js fails its signature and these must be reviewed again.
 */
import { writeFileSync } from 'node:fs';
import { loadGlbMeshes } from './glb-mesh.mjs';

const meshes = loadGlbMeshes('assets/z-anatomy-skeleton.glb');

function measure(name) {
  const m = meshes.find((x) => x.name === name);
  const P = m.positions, n = P.length / 3;
  const v = (i) => [P[i * 3], P[i * 3 + 1], P[i * 3 + 2]];
  const min = [1e9, 1e9, 1e9], max = [-1e9, -1e9, -1e9];
  for (let i = 0; i < n; i++) { const p = v(i); for (let k = 0; k < 3; k++) { min[k] = Math.min(min[k], p[k]); max[k] = Math.max(max[k], p[k]); } }
  const cx = (min[0] + max[0]) / 2, W = max[0] - min[0], D = max[2] - min[2], ymid = (min[1] + max[1]) / 2;
  const pick = (score) => { let b = Infinity, bi = 0; for (let i = 0; i < n; i++) { const s = score(v(i)); if (s < b) { b = s; bi = i; } } return v(bi); };
  /* the vertebral foramen is the largest hole seen from above: the biggest empty circle in the middle band */
  let best = -1, fc = [cx, 0];
  const step = Math.max(W, D) / 60;
  const pts = Array.from({ length: n }, (_, i) => v(i));
  for (let x = cx - W * .15; x <= cx + W * .15; x += step) for (let z = min[2] + D * .2; z <= max[2] - D * .05; z += step) {
    let d = 1e9; for (const p of pts) { const dd = (p[0] - x) ** 2 + (p[2] - z) ** 2; if (dd < d) d = dd; }
    if (d > best) { best = d; fc = [x, z]; }
  }
  const nearXZ = (x, z) => pick((p) => (p[0] - x) ** 2 + (p[2] - z) ** 2 + (p[1] - ymid) ** 2 * .3);
  return {
    spinous: pick((p) => p[2] + Math.abs(p[0] - cx) * .6),
    body: pick((p) => -p[2] + Math.abs(p[0] - cx) * .6),
    transverse: pick((p) => -p[0]),
    foramen: nearXZ(cx, fc[1]),
    pedicle: nearXZ(cx + W * .2, min[2] + D * .5),
    lamina: nearXZ(cx + W * .1, min[2] + D * .2),
    supArtic: pick((p) => -p[1] + Math.abs(p[0] - (cx + W * .25)) * .8 + Math.abs(p[2] - (min[2] + D * .35)) * .8),
    costalUp: pick((p) => -p[1] + Math.abs(p[0] - (cx + W * .18)) + Math.abs(p[2] - (min[2] + D * .62))),
    costalLow: pick((p) => p[1] + Math.abs(p[0] - (cx + W * .18)) + Math.abs(p[2] - (min[2] + D * .62))),
  };
}
const r = (p) => `[${p.map((x) => +x.toFixed(6)).join(',')}]`;
const out = [];
const add = (key, mesh, rows) => out.push(`  ['${key}','${mesh}',[\n${rows.map(([n, p, page]) => `    head('${n}',${r(p)},${page}),`).join('\n')}\n  ]],`);
for (const c of ['C3', 'C4', 'C5', 'C6']) {
  const f = measure(`Vertebra_${c}`);
  add(`vertebra ${c.toLowerCase()}`, `Vertebra_${c}`, [['Vertebral body', f.body, 20], ['Vertebral foramen', f.foramen, 20], ['Pedicle', f.pedicle, 20],
    ['Transverse process', f.transverse, 20], ['Spinous process', f.spinous, 20], ['Lamina', f.lamina, 20], ['Superior articular process', f.supArtic, 20]]);
}
for (let t = 1; t <= 12; t++) {
  const f = measure(`Vertebra_T${t}`);
  add(`vertebra t${t}`, `Vertebra_T${t}`, [['Transverse process', f.transverse, 22], ['Superior articular facet', f.supArtic, 22], ['Superior costal facet', f.costalUp, 22], ['Inferior costal facet', f.costalLow, 22]]);
}
for (let l = 1; l <= 5; l++) {
  const f = measure(`Vertebra_L${l}`);
  add(`vertebra l${l}`, `Vertebra_L${l}`, [['Vertebral body', f.body, 26], ['Vertebral foramen', f.foramen, 26], ['Lamina', f.lamina, 26], ['Articular facet', f.supArtic, 26]]);
}
const a = measure('Atlas_(C1)');
add('atlas (c1)', 'Atlas_(C1)', [['Superior articular facet', a.supArtic, 19]]);
writeFileSync('work/bone-landmark-vertebrae.mjs', `/* GENERATED by work/derive-vertebra-landmarks.mjs, then reviewed on screen. See that file's header. */
const head = (name, target, page, label = name) => [name, target, 'hss.hnt.2026', page, { diagram: label }];
export const VERTEBRA_LANDMARKS = [
${out.join('\n')}
];
`);
console.log('wrote work/bone-landmark-vertebrae.mjs', out.length, 'vertebrae');
