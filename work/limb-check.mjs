/*
 * Limb vessels check -- the BetterHeart limb frames against the explorer's own circulatory layer, offline.
 *
 *   node work/limb-check.mjs          check
 *   node work/limb-check.mjs --write  rewrite outputs/limb/alignment.js from work/limb-boxes.json, then check
 *
 * BetterHeart's arm and leg models were cut from the same dolasim.glb as the explorer's circulatory layer and
 * then moved into a frame of their own: limb = scale * (body - origin), no rotation. The pages declare `scale`
 * and `origin` in their manifests (kept, with the vessel bounding boxes, in work/limb-boxes.json by
 * work/sync-betterheart.mjs). This script proves, against outputs/assets/dolasim.glb, that:
 *   1. outputs/limb/alignment.js still says what the manifests say
 *   2. a fresh least-squares fit of same-named vessels gives slope = scale and intercept = -scale * origin
 *   3. every centre-line route lies inside the same-named vessel (route frame -> body frame -> the GLB's box)
 *   4. the routes cover the vessels a procedure walks (named in leg-proc.js)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { boxesIn } from './lib/mesh-names.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const LIMB = join(ROOT, 'outputs', 'limb');
let fail = 0;
const ok = (c, m) => { console.log(`  ${c ? 'ok  ' : 'FAIL'} ${m}`); if (!c) fail++; };
const norm = (s) => String(s).replace(/_/g, ' ').replace(/\s+/g, ' ').trim().toLowerCase();
const boxes = JSON.parse(readFileSync(join(ROOT, 'work', 'limb-boxes.json'), 'utf8'));

if (process.argv.includes('--write')) {
  const frames = Object.fromEntries(Object.entries(boxes).map(([k, v]) => [k, { scale: v.scale, origin: v.origin }]));
  writeFileSync(join(LIMB, 'alignment.js'), `/* GENERATED by work/limb-check.mjs --write from work/limb-boxes.json. Do not edit.
 * Each limb page's frame is limb = scale * (body - origin), no rotation, where "body" is the explorer's
 * circulatory-layer frame (dolasim.glb). A group in a limb's own frame therefore takes scale 1/scale and
 * position origin (scale first, then translate) to sit on the body. */
export const LIMB_FRAMES = ${JSON.stringify(frames)};
`.replace(/\n/g, '\r\n'));
  console.log('wrote outputs/limb/alignment.js');
}

const { LIMB_FRAMES } = await import(pathToFileURL(join(LIMB, 'alignment.js')).href);
const host = new Map([...boxesIn('assets/dolasim.glb')].map(([k, v]) => [norm(k), v]));
const keyOf = (name, side) => norm(name + (side === 'M' ? '' : '.' + side.toLowerCase()));

for (const page of ['upper', 'lower']) {
  console.log(page);
  const b = boxes[page], f = LIMB_FRAMES[page];
  ok(!!b && !!f && f.scale === b.scale && f.origin.every((v, i) => v === b.origin[i]), `alignment.js ${JSON.stringify(f)} matches the manifest's ${JSON.stringify(b && { scale: b.scale, origin: b.origin })}`);

  /* the manifest has one box per mesh; a name+side can have several */
  const union = new Map();
  for (const v of b.vessels) {
    const k = keyOf(v.name, v.side), u = union.get(k) || [[1e9, 1e9, 1e9], [-1e9, -1e9, -1e9]];
    for (let i = 0; i < 3; i++) { u[0][i] = Math.min(u[0][i], v.min[i]); u[1][i] = Math.max(u[1][i], v.max[i]); }
    union.set(k, u);
  }
  const rows = [];
  for (const [k, a] of union) { const h = host.get(k); if (h) rows.push({ k, a, h }); }
  ok(rows.length >= 100, `${rows.length} of ${union.size} vessels match a same-named mesh in dolasim.glb (need >= 100)`);
  for (let ax = 0; ax < 3; ax++) {
    const xs = rows.map((r) => (r.h[0][ax] + r.h[1][ax]) / 2), ys = rows.map((r) => (r.a[0][ax] + r.a[1][ax]) / 2);
    const n = xs.length, mx = xs.reduce((s, v) => s + v) / n, my = ys.reduce((s, v) => s + v) / n;
    let sxy = 0, sxx = 0; for (let i = 0; i < n; i++) { sxy += (xs[i] - mx) * (ys[i] - my); sxx += (xs[i] - mx) ** 2; }
    const slope = sxy / sxx, ic = my - slope * mx, want = -f.scale * f.origin[ax];
    let worst = 0; for (let i = 0; i < n; i++) worst = Math.max(worst, Math.abs(f.scale * (xs[i] - f.origin[ax]) - ys[i]));
    ok(Math.abs(slope - f.scale) < 0.1, `axis ${'xyz'[ax]}: slope ${slope.toFixed(3)} is the declared scale ${f.scale}`);
    ok(Math.abs(ic - want) < 0.06, `axis ${'xyz'[ax]}: intercept ${ic.toFixed(3)} is -scale*origin = ${want.toFixed(3)}`);
    ok(worst < 0.25, `axis ${'xyz'[ax]}: worst centre residual with the declared frame ${worst.toFixed(3)} limb units (< 0.25 = 3 cm of body)`);
  }

  /* routes */
  const routes = JSON.parse(readFileSync(join(LIMB, `routes-${page}.json`), 'utf8')).routes;
  let outside = 0, checked = 0, worstOut = 0, worstName = '';
  const margin = 0.2;
  for (const r of routes) {
    const u = union.get(keyOf(r.key, r.side));
    if (!u) continue;
    checked++;
    for (const p of r.pts) for (let i = 0; i < 3; i++) {
      const out = Math.max(u[0][i] - margin - p[i], p[i] - (u[1][i] + margin), 0);
      if (out > 0) { outside++; if (out > worstOut) { worstOut = out; worstName = `${r.key}/${r.side}`; } break; }
    }
  }
  ok(checked >= routes.length * 0.9, `${checked} of ${routes.length} routes name a vessel of the manifest`);
  ok(outside === 0, `every route point lies within 0.2 of its vessel's box${outside ? ` -- ${outside} do, worst ${worstOut.toFixed(2)} (${worstName})` : ''}`);
  /* and in the viewer's frame: the route's first point against the GLB's box for that vessel */
  let off = 0, seen = 0;
  for (const r of routes) {
    const h = host.get(keyOf(r.key, r.side)); if (!h) continue;
    const p = r.pts[Math.floor(r.pts.length / 2)].map((v, i) => v / f.scale + f.origin[i]);
    seen++;
    if (p.some((v, i) => v < h[0][i] - 0.06 || v > h[1][i] + 0.06)) off++;
  }
  ok(seen > 0 && off / seen < 0.02, `${seen - off} of ${seen} route midpoints, moved into the body frame, lie inside the GLB's own vessel box`);
}

/* the vessels a procedure walks must have a route on the right side */
const proc = readFileSync(join(LIMB, 'leg-proc.js'), 'utf8');
const lower = JSON.parse(readFileSync(join(LIMB, 'routes-lower.json'), 'utf8')).routes;
console.log('procedures');
for (const m of proc.matchAll(/route\('([^']+)','([A-Z])'\)/g)) {
  ok(lower.some((r) => r.key === m[1] && r.side === m[2]), `route "${m[1]}" (${m[2]}) exists`);
}
console.log(fail ? `\n${fail} FAILED` : '\nALL PASS');
process.exitCode = fail ? 1 : 0;
