/* Current lecture names supplement the atlas's older study-unit grouping.
 * Full extracted pages stay in the ignored local cache; the public payload
 * contains structure names and file/page evidence only, never the decks.
 */
import { readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join } from 'node:path';
import { collectStructures } from './lib/mesh-names.mjs';
import { extractText } from './lib/doc-text.mjs';
import { normaliseSearch } from '../outputs/search-name.js';
import { UNITS } from '../outputs/mesh-index.js';

const folder=process.argv.includes('--root')?process.argv[process.argv.indexOf('--root')+1]
  :'C:/Users/leung/iCloudDrive/Human Anatomy';
const cachePath='work/.source-text/viewer-lecture-scope.json';
const old=existsSync(cachePath)?JSON.parse(readFileSync(cachePath,'utf8')):[];
const norm=s=>normaliseSearch(String(s).replace(/\([^)]*\)/g,' '))
  .replace(/\bmetacarpals\b/g,'metacarpal').replace(/\bmetatarsals\b/g,'metatarsal');
const docs=[];
for(const file of readdirSync(folder).filter(n=>/\.pdf$/i.test(n)).sort()){
  const path=join(folder,file),sha256=createHash('sha256').update(readFileSync(path)).digest('hex');
  let doc=old.find(d=>d.file===file&&d.sha256===sha256);
  if(!doc){const result=extractText(path);if(!result.ok)throw new Error(`${file}: ${result.why}`);doc={file,sha256,pages:result.pages};}
  docs.push(doc);
}
mkdirSync('work/.source-text',{recursive:true});writeFileSync(cachePath,JSON.stringify(docs));
const pages=docs.flatMap(d=>d.pages.map((text,i)=>({file:d.file,page:i+1,text:' '+norm(text)+' '})));
const rows=collectStructures().rows;
const candidates=[...rows,...UNITS.filter(u=>!rows.some(r=>r.layer===u.layer&&r.name===u.label))
  .map(u=>({name:u.label,layer:u.layer,group:true}))];
const names=[];
const named=(phrase,r)=>pages.find(p=>{
  const at=p.text.indexOf(' '+phrase+' ');if(at<0)return false;
  const next=p.text.slice(at+phrase.length+2).split(' ')[0];
  if(/bone$/.test(r.name)&&!/bone$/.test(phrase)
    &&!/Week [23]_|Head_Neck_Trunk|MusculoskeletalSystem/i.test(p.file))return false;
  if(/bone$/.test(r.name)&&/^(?:lobe|cortex|plane|sinus)$/.test(next))return false;
  if(/muscle$/.test(r.name)&&/^(?:ligament|nerve|artery|vein|fascia)$/.test(next))return false;
  return true;
});
for(const r of candidates){
  const phrase=norm(r.name),short=phrase.replace(/\s+(?:muscle|bone)$/,'');
  const variants=[phrase,...(short!==phrase?[short]:[])];
  const found=variants.filter(v=>v.length>3).map(v=>named(v,r)).find(Boolean);
  if(found)names.push({layer:r.layer,name:r.name,file:found.file,page:found.page,...(r.group?{evidence:'named group'}:{})});
}
// The model represents these joints by their articular capsules. Name the
// lecture joint, without asking the student to learn an unmentioned capsule.
for(const r of rows.filter(r=>r.layer==='joint'&&/^Articular capsules? of /i.test(r.name))){
  const joint=r.name.replace(/^Articular capsules? of /i,'');
  const found=named(norm(joint),r);if(!found)continue;
  const entry={layer:r.layer,name:r.name,displayName:joint[0].toUpperCase()+joint.slice(1),
    file:found.file,page:found.page,evidence:'joint represented by articular capsule'};
  const old=names.findIndex(n=>n.layer===r.layer&&n.name===r.name);
  if(old<0)names.push(entry);else names[old]=entry;
}
// These diagrams name the numbered sets rather than spelling every GLB name.
// A set does not justify an unmentioned depression, muscle part or branch.
const families=[
  {re:/^(?:First|Second|Third|Fourth|Fifth) metatarsal bone$/,file:'Week 2_LL _2026_CKK_upload.pdf',page:12,term:'Metatarsal'},
  {re:/^(?:Proximal|Middle|Distal) phalanx of (?:first|second|third|fourth|fifth) finger of foot$/,file:'Week 2_LL _2026_CKK_upload.pdf',page:12,term:'phalanx'},
  {re:/^(?:First|Second|Third|Fourth|Fifth) metacarpal bone$/,file:'Week 3_UL_2026_CKK_upload.pdf',page:14,term:'metacarpal bones'},
  {re:/^(?:Proximal|Middle|Distal) phalanx of (?:first|second|third|fourth|fifth) finger of hand$/,file:'Week 3_UL_2026_CKK_upload.pdf',page:14,term:'phalanx'},
  {re:/^(?:Medial|Intermediate|Lateral) cuneiform bone$/,file:'Week 2_LL _2026_CKK_upload.pdf',page:12,term:'Cuneiform bones'},
];
for(const f of families){
  const doc=docs.find(d=>d.file===f.file);if(!doc)throw new Error(`Missing ${f.file}`);
  if(f.term&&!norm(doc.pages[f.page-1]).includes(norm(f.term)))throw new Error(`Missing family evidence: ${f.term}`);
  for(const r of rows.filter(r=>r.layer==='skeleton'&&f.re.test(r.name)))
    if(!names.some(n=>n.layer===r.layer&&n.name===r.name))names.push({layer:r.layer,name:r.name,file:f.file,page:f.page,evidence:f.diagram?'reviewed diagram set':'named set'});
}
names.sort((a,b)=>a.layer.localeCompare(b.layer)||a.name.localeCompare(b.name));
const output='/* GENERATED by work/build-viewer-lecture-names.mjs. Names and source pages only. */\n'
  +`export const VIEWER_LECTURE_SOURCES = ${JSON.stringify(docs.map(({file,sha256,pages})=>({file,sha256,pages:pages.length})),null,2)};\n`
  +`export const VIEWER_LECTURE_NAMES = ${JSON.stringify(names,null,2)};\n`
  +`const lectureMap=new Map(VIEWER_LECTURE_NAMES.map(r=>[r.layer+'|'+r.name.toLowerCase(),r]));
export function lectureRow(row){
  const own=lectureMap.get(row.layer+'|'+row.name.toLowerCase());
  const family=lectureMap.get(row.layer+'|'+row.unit.toLowerCase());
  const lectureSource=own||family;
  if(!lectureSource)return row;
  const shown=own?.displayName?{name:own.displayName,unit:own.displayName}:{};
  if(!own||row.unitKind==='course')return {...row,...shown,lectureSource};
  return {...row,...shown,unit:own.displayName||row.name,unitId:'lecture:'+row.name.toLowerCase().replace(/[^a-z0-9]/g,''),
    unitKind:'course',unitSize:1,isUnit:true,tier:0,lectureSource};
}
`;
if(process.argv.includes('--check')){
  if(readFileSync('outputs/viewer-lecture-names.js','utf8')!==output)throw new Error('Viewer lecture names need regeneration');
}else writeFileSync('outputs/viewer-lecture-names.js',output);
console.log(JSON.stringify({files:docs.length,pages:pages.length,names:names.length,layers:Object.fromEntries([...new Set(names.map(n=>n.layer))].map(k=>[k,names.filter(n=>n.layer===k).length]))}));
