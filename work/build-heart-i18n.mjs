/*
 * Build outputs/heart/i18n-en.js -- the English for every Chinese string the ported modules carry.
 *
 *   node work/build-heart-i18n.mjs            report: strings with no English
 *   node work/build-heart-i18n.mjs --write    write the dictionary
 *
 * The English comes from the site's own i18n/en.json (Chinese -> English). Anything it lacks is taken from
 * work/heart-i18n-overrides.json (ours, wins over the site's). A string in neither is listed and the run
 * fails, so a ported module can never ship an untranslated label by accident.
 */
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { mapStrings, hasCjk, VERSIONS } from './lib/bh-js.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const files = [...Object.keys(VERSIONS).map((f) => join(ROOT, 'outputs', 'heart', f)), join(ROOT, 'outputs', 'studio', 'heart-atlas.js'), join(ROOT, 'outputs', 'heart', 'heart-panels.js')]
  .filter(existsSync);
const upstream = await (await fetch('https://skypray.synology.me/betterheart/heart-anatomy/i18n/en.json')).json();
const over = existsSync(join(ROOT, 'work', 'heart-i18n-overrides.json')) ? JSON.parse(readFileSync(join(ROOT, 'work', 'heart-i18n-overrides.json'), 'utf8')) : {};

const keys = new Set();
for (const f of files) {
  const src = readFileSync(f, 'utf8');
  mapStrings(src, ({ body }) => { if (hasCjk(body)) keys.add(body.replace(/\\(['"\\])/g, '$1').replace(/\\n/g, '\n')); });
}
/* The site's English is American; the app is British (oesophagus, depolarisation). Only stems seen in the
   site's heart vocabulary, so a word like "size" is never touched. An override in work/heart-i18n-overrides.json
   is taken as written. */
const UK = [[/esophag/g, 'oesophag'], [/Esophag/g, 'Oesophag'], [/edema/g, 'oedema'], [/Edema/g, 'Oedema'], [/ischem/g, 'ischaem'], [/Ischem/g, 'Ischaem'],
  [/hemodynamic/g, 'haemodynamic'], [/Hemodynamic/g, 'Haemodynamic'], [/hemorrhag/g, 'haemorrhag'], [/anemi/g, 'anaemi'],
  [/(polar|ventricular|equal|normal|stabil|synchron|visual|minim|maxim|recogn|categor|character|general|local|optim|summar|util|real)iz(ation|e|ed|es|ing)/g, '$1is$2']];
const british = (s) => UK.reduce((t, [re, to]) => t.replace(re, to), s);
const dict = {}, missing = [];
for (const k of [...keys].sort()) {
  const v = over[k] ?? (upstream[k] === undefined ? undefined : british(upstream[k]));
  if (v === undefined) missing.push(k); else dict[k] = v;
}
console.log(`${keys.size} Chinese strings in ${files.length} files: ${Object.keys(dict).length} translated, ${missing.length} missing`);
for (const k of missing) console.log('  MISSING ' + JSON.stringify(k));
if (process.argv.includes('--write')) {
  writeFileSync(join(ROOT, 'outputs', 'heart', 'i18n-en.js'),
    `/* GENERATED by work/build-heart-i18n.mjs --write. Do not edit. English for the Chinese strings in the modules ported from BetterHeart. */\nexport const EN = ${JSON.stringify(dict, null, 1)};\n`.replace(/\n/g, '\r\n'));
  console.log('wrote outputs/heart/i18n-en.js');
}
process.exitCode = missing.length ? 1 : 0;
