export const NOT_A_TERM = new Set(['arbitrary', 'auxiliary', 'boundary', 'category', 'chemist', 'chemists', 'conduct', 'conducting', 'conduction', 'conductor', 'conducts', 'consider', 'considered', 'consist', 'consisting', 'consists', 'contain', 'container', 'contains', 'contract', 'contraction', 'contracts', 'contrary', 'conversion', 'converted', 'converts', 'customary', 'february', 'glossary', 'imaginary', 'interfere', 'interferes', 'involuntary', 'january', 'library', 'military', 'momentary', 'monetary', 'necessary', 'ordinary', 'precision', 'prepare', 'prepared', 'prepares', 'preparing', 'present', 'presented', 'presents', 'primary', 'products', 'protect', 'protects', 'represent', 'salary', 'secondary', 'sedentary', 'subtract', 'subtracts', 'summary', 'temporary', 'transfer', 'transferred', 'transferring', 'transfers', 'transport', 'voluntary']);

/* Connecting vowels and grammatical tails: real, but not word parts. */
const ENDINGS = {
  o: 'joining vowel', a: 'ending', al: 'relating to', ar: 'relating to', ic: 'relating to',
  us: 'ending', um: 'ending', es: 'plural', s: 'plural', e: 'ending', is: 'ending',
  ary: 'relating to', ous: 'full of', ine: 'relating to', id: 'ending', ior: 'more, -er',
  eal: 'relating to', tic: 'relating to', ism: 'condition', ed: 'past', ing: 'ongoing',
};

const STEMS = Object.keys(WORD_PARTS).sort((a, b) => b.length - a.length);

/*
 * Longest-match segmentation, left to right.
 *
 * Returns null unless the WHOLE word resolves into known parts and recognised
 * endings. A partial match is worse than none: it invites the learner to trust
 * a split that is really a coincidence.
 */
export function decompose(word) {
  const raw = String(word || '').toLowerCase().replace(/[^a-z]/g, '');
  if (raw.length < 7 || NOT_A_TERM.has(raw)) return null;
  const seg = [];
  let i = 0;
  while (i < raw.length) {
    const hit = STEMS.find((st) => raw.startsWith(st, i));
    if (hit) {
      const [kind, forms, means] = WORD_PARTS[hit];
      seg.push({ text: hit, kind, forms, means });
      i += hit.length;
      continue;
    }
    const tail = raw.slice(i);
    const end = Object.keys(ENDINGS).filter((e) => tail === e || (e === 'o' && tail.startsWith('o')))
      .sort((a, b) => b.length - a.length)[0];
    if (end === 'o') { seg.push({ text: 'o', kind: 'link', means: ENDINGS.o }); i += 1; continue; }
    if (end) { seg.push({ text: end, kind: 'ending', means: ENDINGS[end] }); i += end.length; continue; }
    return null;   /* leftover letters: the split is a coincidence, not a reading */
  }
  const known = seg.filter((s) => s.kind === 'root' || s.kind === 'prefix' || s.kind === 'suffix');
  if (known.length < 2) return null;
  const cover = known.reduce((n, s) => n + s.text.length, 0) / raw.length;
  if (cover < 0.66) return null;
  return { word: String(word), parts: seg };
}

/* A one-line reading of the term, built from the parts: "tongue + pharynx + relating to". */
export function readingOf(d) {
  if (!d) return '';
  return d.parts.filter((p) => p.kind !== 'link' && p.kind !== 'ending').map((p) => p.means.split(',')[0]).join(' + ');
}

/*
 * A single word part, looked up as it is written in the text: 'epi-', '-graphy',
 * 'cardi/o'. decompose() answers "what is this long word made of"; this answers
 * "what does this one piece mean", which is what the terminology items are
 * actually a list of.
 */
export function partOf(token) {
  const raw = String(token || '').toLowerCase().trim();
  if (!raw) return null;
  const stem = raw.replace(/\/[oi]$/, '').replace(/^-+|-+$/g, '');
  if (stem.length < 2) return null;
  const rec = WORD_PARTS[stem];
  if (!rec) return null;
  const [kind, forms, means] = rec;
  return { stem, kind, forms, means, written: raw };
}

/* True for tokens written as a word part rather than as a whole word. */
export function looksLikePart(token) {
  return /^-|-$|\/[oi]$/.test(String(token || '').trim());
}
