/*
 * Lookup.
 *
 * Word parts are written several ways — `-itis`, `oste/o`, `epi-` — and reduce
 * to the bare stem. Whole words are tried as written and then folded through
 * the same plural and adjective endings term-notes.js uses, so a form the
 * corpus happens to use that is not listed above still resolves.
 */
const FOLDS = [[/i$/, 'us'], [/ae$/, 'a'], [/es$/, 'e'], [/s$/, ''], [/al$/, ''], [/ic$/, '']];

/*
 * Adjectives do not fold to their noun with the list above — pericardial misses
 * through /al$/ -> "pericardi" (not a key) and thoracic through /ic$/ ->
 * "thorac" (not a key). So strip the adjective suffix, then put the noun
 * endings back and accept the FIRST key that exists. Nothing is invented here:
 * an adjective only resolves when TERM_GLOSS already holds the noun.
 */
const ADJ_SUFFIXES = [[/ial$/, ''], [/eal$/, ''], [/al$/, ''], [/ous$/, ''], [/ary$/, ''], [/ar$/, ''], [/ic$/, ''], [/ac$/, '']];
const NOUN_SUFFIXES = ['um', 'us', 'a', 'is', 'e', 'ium', 'ax'];

function foldAdjective(word) {
  for (const [re] of ADJ_SUFFIXES) {
    if (!re.test(word)) continue;
    const stem = word.replace(re, '');
    if (stem.length < 4) continue;
    for (const s of NOUN_SUFFIXES) {
      const target = stem + s;
      if (target !== word && TERM_GLOSS[target]) return target;
    }
  }
  return null;
}

/*
 * Irregulars the mechanical fold cannot reach — abdominal is "abdomen", not
 * "abdomin" plus a noun ending. The value must be a key that exists in
 * TERM_GLOSS; it is checked before the folds so it wins where both would match.
 */
const ALIASES = {
  abdominal: 'abdomen',
  pelvic: 'pelvis',
  cardiac: 'heart',
  /* third-declension c→x: thorac- appends to nothing, the noun is thorax */
  thoracic: 'thorax',
};

export function termGloss(token) {
  const raw = String(token || '').toLowerCase().trim();
  if (!raw) return null;
  const hit = (k) => ({ key: k, meaning: TERM_GLOSS[k][0], zh: TERM_GLOSS[k][1] });

  const word = raw.replace(/[^a-z]/g, '');
  if (TERM_GLOSS[word]) return hit(word);

  /* written as a part: drop the hyphens and the /o or /i combining tail */
  const stem = raw.replace(/\/[oi]$/, '').replace(/^-+|-+$/g, '').replace(/[^a-z]/g, '');
  if (stem !== word && TERM_GLOSS[stem]) return hit(stem);

  const alias = ALIASES[word];
  if (alias && TERM_GLOSS[alias]) return hit(alias);

  for (const [from, to] of FOLDS) {
    const alt = word.replace(from, to);
    if (alt !== word && TERM_GLOSS[alt]) return hit(alt);
  }

  const noun = foldAdjective(word);
  if (noun) return hit(noun);

  return null;
}

